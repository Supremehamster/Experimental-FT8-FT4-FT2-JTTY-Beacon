#!/usr/bin/env python3
"""
encode_jtty.py — host encoder for JTTY callsign-action "CQ <call> CQ" (one frame, EOM=1).

Protocol (WSJT-X 3.2 / 3.3, verified against jttyaf.app/jtty + mfsk-core docs):
  pack28 (same as FT8) + action CQ (i2=0,n2=0) → 32-bit word
  + reserved0 + EOM → 34-bit payload
  CRC-12 poly 0x80F (MSB-first, init 0, no reflect/XOR) → 46 info bits
  TBCC r=1/2 K=10 gens 1167/1545 octal, tail-biting → Gray map → 46 data tones
  Frame = sync(13) + data(46) = 59 symbols

Golden checks (mfsk-core crc/tbcc unit tests):
  - rem([0]*34) == 0
  - rem(payload with only last bit=1) == 0x80F
  - rem(info) == 0 after append
  - TBCC path closes; all-zero info → all-zero data tones

Usage:
  python3 encode_jtty.py N0TOK              # positional call (preferred)
  python3 encode_jtty.py --call N0TOK       # same
  python3 encode_jtty.py --stdout N0TOK     # C array only
  python3 encode_jtty.py --out path.h CALL  # write header to path
"""
from __future__ import annotations
import argparse
import os
import sys

POLY = 0x80F
SYNC = [0, 2, 2, 3, 0, 0, 3, 2, 1, 3, 1, 2, 0]
GENS = [0o1167, 0o1545]
MEMORY = 9
STATE_MASK = (1 << MEMORY) - 1
REGISTER_MASK = (1 << (MEMORY + 1)) - 1


def pack28(call: str) -> int:
    """FT8/JTTY standard-call pack28 (NTOKENS + MAX22 + n)."""
    c6 = list("      ")
    n = len(call)
    if n < 3 or n > 6:
        raise ValueError(f"unsupported call {call!r}")
    if call[2].isdigit():
        for i, ch in enumerate(call):
            c6[i] = ch
    elif call[1].isdigit() and n <= 5:
        for i, ch in enumerate(call):
            c6[i + 1] = ch
    else:
        raise ValueError(f"unsupported call {call!r}")
    A1 = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    A2 = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    A3 = "0123456789"
    A4 = " ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    i1, i2, i3 = A1.index(c6[0]), A2.index(c6[1]), A3.index(c6[2])
    i4, i5, i6 = A4.index(c6[3]), A4.index(c6[4]), A4.index(c6[5])
    v = ((((i1 * 36 + i2) * 10 + i3) * 27 + i4) * 27 + i5) * 27 + i6
    return 2063592 + 4194304 + v


def crc12_remainder(bits) -> int:
    reg = 0
    for b in bits:
        reg ^= (b & 1) << 11
        reg = ((reg << 1) ^ POLY) if (reg & 0x800) else (reg << 1)
        reg &= 0xFFF
    return reg


def payload_cq_call_cq(call: str, eom: bool = True) -> list[int]:
    """Callsign action CQ <call> CQ: i2=0, n2=0; reserved=0; EOM as given."""
    n28 = pack28(call)
    word = (n28 << 4) & 0xFFFFFFFF  # action bits 0
    bits = [((word >> (31 - i)) & 1) for i in range(32)]
    bits.append(0)  # reserved
    bits.append(1 if eom else 0)
    return bits


def append_crc(payload: list[int]) -> list[int]:
    crc = crc12_remainder(payload)
    return payload + [((crc >> (11 - i)) & 1) for i in range(12)]


def tbcc_encode(info: list[int]) -> list[int]:
    start = 0
    for b in info[-MEMORY:]:
        start = ((start << 1) | (b & 1)) & STATE_MASK
    state = start
    tones = []
    for bit in info:
        register = ((state << 1) | (bit & 1)) & REGISTER_MASK
        b0 = bin(register & GENS[0]).count("1") & 1
        b1 = bin(register & GENS[1]).count("1") & 1
        tones.append(2 * b0 + (b0 ^ b1))  # Gray: 00→0,01→1,11→2,10→3
        state = register & STATE_MASK
    if state != start:
        raise RuntimeError("TBCC path did not close")
    return tones


def encode_frame(call: str = "N0TOK") -> list[int]:
    payload = payload_cq_call_cq(call, eom=True)
    info = append_crc(payload)
    if crc12_remainder(info) != 0:
        raise RuntimeError("CRC self-check failed")
    data = tbcc_encode(info)
    frame = SYNC + data
    assert len(frame) == 59 and all(t < 4 for t in frame)
    return frame, payload, info, data


# Fixed golden vector for example callsign action "CQ N0TOK CQ" (pack28=0xa4cb6e).
# Regenerate intentionally if protocol docs change.
N0TOK_GOLDEN = [
    0, 2, 2, 3, 0, 0, 3, 2, 1, 3, 1, 2, 0,
    3, 0, 0, 2, 1, 0, 3, 1, 1, 0, 2, 0, 1, 0, 2, 2, 1, 3, 2, 3, 3, 1, 2, 0,
    1, 2, 3, 2, 1, 0, 0, 2, 3, 1, 2, 1, 3, 2, 3, 1, 2, 0, 1, 1, 1, 3,
]


def self_test() -> None:
    assert crc12_remainder([0] * 34) == 0
    p = [0] * 34
    p[33] = 1
    assert crc12_remainder(p) == POLY
    assert tbcc_encode([0] * 46) == [0] * 46
    frame, payload, info, data = encode_frame("N0TOK")
    assert crc12_remainder(info) == 0
    assert len(frame) == 59
    n28 = pack28("N0TOK")
    assert n28 == 0xA4CB6E, hex(n28)
    assert frame == N0TOK_GOLDEN, (frame, N0TOK_GOLDEN)
    print(f"self_test OK: CRC unit tests, TBCC zero, N0TOK golden (pack28=0x{n28:x})")


def emit_header(frame: list[int], path: str, call: str = "N0TOK") -> None:
    lines = [
        "/*",
        " * jtty_tones.h — precomputed JTTY channel symbols for callsign action",
        f' * "CQ {call} CQ" (one frame, EOM=1).',
        " * Generated by extras/encode_jtty.py (pack28 + CRC-12 0x80F + TBCC 1167/1545).",
        " * Protocol: WSJT-X 3.2/3.3 JTTY (jttyaf.app/jtty, mfsk-core). Not FT2D/FT2W/JT65/RTTY.",
        f" * Regenerate: python3 extras/encode_jtty.py {call}",
        " */",
        "#pragma once",
        "#include <avr/pgmspace.h>",
        "#include <stdint.h>",
        "",
        "#define JTTY_SYMBOL_COUNT 59",
        "",
        "static const uint8_t JTTY_TONES[JTTY_SYMBOL_COUNT] PROGMEM = {",
    ]
    row = []
    for i, t in enumerate(frame):
        row.append(str(t))
        if len(row) == 13 or i == len(frame) - 1:
            lines.append("  " + ",".join(row) + ("," if i < len(frame) - 1 else ""))
            row = []
    lines.append("};")
    lines.append("")
    text = "\n".join(lines) + "\n"
    with open(path, "w") as f:
        f.write(text)
    print(f"wrote {path} ({len(frame)} symbols)")


def main() -> int:
    ap = argparse.ArgumentParser(description="Encode JTTY callsign-action CQ <call> CQ tones")
    ap.add_argument("call_pos", nargs="?", default="", help="Callsign (e.g. N0TOK)")
    ap.add_argument("--call", default="", help="Callsign (alternative to positional)")
    ap.add_argument("--stdout", action="store_true")
    ap.add_argument("--out", default="")
    args = ap.parse_args()
    call = (args.call_pos or args.call or "N0TOK").upper()
    self_test()
    frame, payload, info, data = encode_frame(call)
    n28 = pack28(call)
    print(f"call={call} pack28={n28} (0x{n28:x})")
    print(f"payload34={''.join(map(str, payload))}")
    print(f"info46   ={''.join(map(str, info))}")
    print(f"data46   ={data}")
    print(f"frame59  ={frame}")
    if args.stdout:
        print(",".join(map(str, frame)))
        return 0
    here = os.path.dirname(os.path.abspath(__file__))
    sketch = os.path.dirname(here)
    out = args.out or os.path.join(sketch, "jtty_tones.h")
    emit_header(frame, out, call=call)
    return 0


if __name__ == "__main__":
    sys.exit(main())
